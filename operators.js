// 1: Arithmatic Oparators

// + Addition
// - Substraction
// * Multiplication
// / Division
// % Modulus (remainder)
// ** Expnentiation (jibaar)

let x = 20;
let y = 4;

console.log(x + y);
console.log(x - y);
console.log(x * y);
console.log(x / y);
console.log(x % y);
console.log(x ** y);

// 2: Comparison Oparators

// ==  Equal to (loose equality)
// === Strict equal(same value and type)
// !=  Not equal to (loose)
// !=== Not equal to (strict)
// > Greater than
// < Less than
// >= Greater than or equal to
// <= less than or equal to

let x = 20;
let y = 4;

console.log(x == y);
console.log(x === y);
console.log(x != y);
console.log(x !== y);
console.log(x > y);
console.log(x < y);
console.log(x >= y);
console.log(x <= y);

// 3: Logical Operators

// && Logical AND
// || Logical OR
// !  Logical NOT

let x = true;
let y = false;

console.log(x && y);
console.log(x || y);
console.log(!x);
console.log(!y);

// 4: Assignment Operators

// = simple assignment
// += add and assign
// -= substract and assign
// *= multiply and assign
// /= divide and assign
// %= modulus and assign
// **= exponenriate and assign

let tiro = 50;

tiro += 30;
tiro -= 20;
tiro *= 5;
tiro /= 10;
tiro %= 2;
tiro **= 8;

console.log(tiro);
